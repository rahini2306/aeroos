"""Regenerate real sample input/output artifacts with the compiled engine."""
import json
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))
sys.path.insert(0,str(ROOT/'tests'))
from scenarios import scenario,NAMES,BANKER,DEADLOCK,PAGING,CONTIGUOUS
from test_engine import engine,workload

def write(path,value):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(value,indent=2)+'\n')

if __name__=='__main__':
    presets={'normal':scenario(),'chaos':scenario('Chaos Mode'),'scheduler-example':workload(),'banker':BANKER,'deadlock':{**DEADLOCK,'recover':True},'paging':PAGING,'contiguous':CONTIGUOUS,'synchronization':dict(mode='mutex',threads=4,iterations=20)}
    for name,value in presets.items():write(ROOT/'data/scenarios'/f'{name}.json',value)
    for name in NAMES:write(ROOT/'data/scenarios'/(name.lower().replace(' ','-')+'.json'),scenario(name))
    summary={}
    for name in ['normal','chaos']:
        r=engine('airport',presets[name]);summary[name]=dict(metrics=r['metrics'],resource_metrics=r['resource_metrics'])
    summary['scheduler']={a:engine('schedule',workload(a))['metrics'] for a in ['fcfs','sjf','srtf','priority','priority_preemptive','rr','hrrn','mlq','mlfq']}
    summary['paging']={a:engine('memory',{**PAGING,'algorithm':a})['page_faults'] for a in ['fifo','lru','optimal']}
    summary['banker']=engine('banker',BANKER)
    summary['deadlock']=engine('deadlock',{**DEADLOCK,'recover':True})
    write(ROOT/'data/results/measured-examples.json',summary)
    rows=['# Measured example results','','Regenerated by `tests/export_examples.py` using the compiled C engine. Seed 42. Units: simulated ticks. These are actual computed example outputs, not embedded dashboard constants.','','| Scenario | Completed | Duration | Average waiting | Throughput |','|---|---:|---:|---:|---:|']
    for name in ['normal','chaos']:
        m=summary[name]['metrics'];rows.append(f"| {name} | {m['completed']} | {m['duration']} | {m['average_waiting']:.5f} | {m['throughput']:.5f} |")
    rows+=['','## Same three-process CPU example','','Input P0=(arrival 0, burst 8, priority 3), P1=(1,4,1), P2=(2,2,2), quantum 2.','','| Policy | Average wait | Average turnaround | Average response | Context switches |','|---|---:|---:|---:|---:|']
    for a,m in summary['scheduler'].items():rows.append(f"| {a} | {m['average_waiting']:.5f} | {m['average_turnaround']:.5f} | {m['average_response']:.5f} | {m['context_switches']} |")
    rows+=['','Paging faults on identical reference string: '+', '.join(f'{a.upper()}={n}' for a,n in summary['paging'].items())+'.','','Full measured vectors, matrices, and resource statistics are in `data/results/measured-examples.json`.']
    (ROOT/'docs/measured-results.md').write_text('\n'.join(rows)+'\n')
    print('Generated reproducible scenario JSON, measured C results, and docs/measured-results.md')
